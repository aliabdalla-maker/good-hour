/**
 * Regenerates docs/DESIGN_TOKENS.md from the Tailwind config.
 *
 * The table it writes was previously typed by hand, and nine of twelve contrast
 * figures were wrong in the second decimal — computed with the 0.03928 sRGB
 * erratum rather than the normative 0.04045. Wrong by too little to flip any
 * pass/fail verdict, and therefore invisible to review forever.
 *
 * Run with: npm run docs:tokens
 * A stale doc fails designAudit.test.ts, so drift surfaces in CI rather than in
 * a reader's assumptions.
 */
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

// TypeScript is loaded via `--import tsx` in the npm script, not registered here:
// tsx refuses to be registered through node:module in Node 20+.
const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
// pathToFileURL, because a bare Windows path is not a valid ESM specifier.
const { parsePalette, renderTokenTable, auditPalette } = await import(
  pathToFileURL(path.join(repoRoot, "packages/web/lib/designAudit.ts")).href
);

const config = readFileSync(path.join(repoRoot, "packages/web/tailwind.config.ts"), "utf8");
const palette = parsePalette(config);

const findings = auditPalette(palette).flatMap((a) => a.findings);
if (findings.length > 0) {
  console.error("Refusing to publish a table for a palette with findings:");
  for (const f of findings) console.error(`  - ${f}`);
  process.exit(1);
}

const doc = `# Design tokens

<!-- GENERATED by scripts/gen-design-tokens.mjs — do not edit by hand.
     Run \`npm run docs:tokens\` after changing the palette. -->

Six semantic families over one shared lightness ramp, generated in OKLCH.

## Why one shared ramp

Each family keeps its own hue and chroma, read from the colours already in use,
but they share a single lightness ramp. That is what makes \`600\` mean the same
visual weight in every family, so a token can be swapped without re-checking
contrast. Before the rework \`brand-600\` sat at 3.74:1 while \`ai-600\` was
5.70:1, which made the tokens quietly non-interchangeable.

An earlier attempt generated the ramp in HSL and was discarded: equal HSL
lightness steps are not equal perceptual steps, so the dark end collapsed to
ΔL* 0.03 between adjacent shades and \`300\` came out visibly more saturated
than its neighbours. In OKLCH the same ramp is even at ΔL* 0.085.

## The invariant

**Step \`600\` clears WCAG AA (4.5:1) for body text on white; \`700\` is the
hover.** Reaching for \`600\` is therefore accessible by default, which is why
every interactive surface uses it.

## Measured contrast

${renderTokenTable(palette)}

Figures are computed by \`contrastRatio\` in \`packages/shared/src/contrast.ts\`
using the normative sRGB linearisation threshold of 0.04045, and are checked
against WCAG's own boundary greys in \`contrast.test.ts\`.

## Enforcement

\`packages/web/lib/designAudit.test.ts\` asserts, on every test run:

- every ramp is monotonic in contrast, and every \`600\` clears AA
- every \`700\` is measurably darker than its \`600\`
- no element's hover colour equals its base colour
- no raw Tailwind default families (\`emerald\`, \`amber\`, \`red\`, \`sky\`, …)
  appear in \`app/\` or \`components/\` — \`slate\` remains the deliberate neutral
- this document matches the palette it describes

Each of those checks is also fed a known-bad fixture that it must flag, because a
checker that has never gone red is unmeasured rather than passing.
`;

writeFileSync(path.join(repoRoot, "docs/DESIGN_TOKENS.md"), doc);
console.log("wrote docs/DESIGN_TOKENS.md");
