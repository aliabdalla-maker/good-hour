/**
 * Generates packages/web/lib/requirementsData.ts from docs/REQUIREMENTS.md.
 *
 * The register is surfaced in the product (admin → Readiness) rather than living
 * only in a markdown file, because a status that nobody sees is a status nobody
 * maintains. The whole reason FR-030 went unnoticed for a full build is that no
 * screen ever showed it.
 *
 * Generated at build time rather than parsed at runtime: the API container does
 * not ship docs/, and a page that silently renders an empty register would be the
 * same silent-empty failure this project keeps re-learning. A stale copy fails
 * requirements.test.ts.
 *
 * Run with: npm run docs:requirements
 */
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const doc = readFileSync(path.join(repoRoot, "docs/REQUIREMENTS.md"), "utf8");

const rows = [];
for (const line of doc.split(/\r?\n/)) {
  if (!line.startsWith("|")) continue;
  const cells = line
    .split("|")
    .slice(1, -1)
    .map((c) => c.trim().replace(/^\*\*|\*\*$/g, ""));
  if (cells.length !== 6) continue;
  if (!/^(FR|NFR|CR)-\d{3}$/.test(cells[0])) continue;
  const [id, requirement, priority, criterion, verdict, evidence] = cells;
  rows.push({
    id,
    family: id.split("-")[0],
    requirement,
    priority,
    criterion,
    verdict,
    // Evidence kinds, so the UI can show HOW something is known, not just that
    // it is claimed. This distinction is the point of the whole register.
    evidenceKinds: ["test", "prod", "manual", "code"].filter((k) =>
      new RegExp("`" + k + ":").test(evidence)
    ),
    evidence: evidence.replace(/`/g, ""),
  });
}

if (rows.length < 45) {
  console.error(`Refusing to generate: only parsed ${rows.length} requirements.`);
  process.exit(1);
}

const body = `// GENERATED by scripts/gen-requirements-data.mjs — do not edit by hand.
// Source of truth: docs/REQUIREMENTS.md. Run \`npm run docs:requirements\`.
// A stale copy fails packages/shared/src/requirements.test.ts.

export type RequirementFamily = "FR" | "NFR" | "CR";
export type RequirementVerdict = "Met" | "Partially met" | "Not met" | "Not started";
export type RequirementPriority = "Must" | "Should" | "Could" | "Won't";
export type EvidenceKind = "test" | "prod" | "manual" | "code";

export interface RequirementRow {
  id: string;
  family: RequirementFamily;
  requirement: string;
  priority: RequirementPriority;
  criterion: string;
  verdict: RequirementVerdict;
  evidenceKinds: EvidenceKind[];
  evidence: string;
}

export const REQUIREMENTS: RequirementRow[] = ${JSON.stringify(rows, null, 2)} as RequirementRow[];

export const FAMILY_LABELS: Record<RequirementFamily, string> = {
  FR: "Functional",
  NFR: "Non-functional",
  CR: "Compliance",
};

/** Strongest evidence backing a row, for sorting and for honest labelling. */
export function strongestEvidence(row: RequirementRow): EvidenceKind | null {
  for (const kind of ["test", "prod", "manual", "code"] as EvidenceKind[]) {
    if (row.evidenceKinds.includes(kind)) return kind;
  }
  return null;
}
`;

writeFileSync(path.join(repoRoot, "packages/web/lib/requirementsData.ts"), body);
console.log(`wrote packages/web/lib/requirementsData.ts (${rows.length} requirements)`);
